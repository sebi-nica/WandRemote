package com.example.wandremote.ui.screens.pointer.layout

/** Every control on the Pointer screen. Behavior is bound to the id, never to a position or shape. */
enum class ControlId {
    KNOB,
    LEFT_CLICK,
    RIGHT_CLICK,
    MOVE_TOGGLE,
    LASER,
    ARROW_LEFT,
    ARROW_RIGHT,
    ARROW_UP,
    ARROW_DOWN,
    RECENTER,
    RECALIBRATE,
}
